  function geojsonToFeatures(geojson) {
    const features = [];
    function addPolygon(coords, props) {
      const ring = coords[0].map(c => [c[1], c[0]]); // [lon,lat] → [lat,lon]
      let lat = 0, lon = 0;
      ring.forEach(p => { lat += p[0]; lon += p[1]; });
      lat /= ring.length; lon /= ring.length;
      features.push({ ring, centroid: [lat, lon], props: props || {} });
    }
    function processGeom(geom, props) {
      if (!geom) return;
      if (geom.type === 'Polygon') addPolygon(geom.coordinates, props);
      else if (geom.type === 'MultiPolygon') geom.coordinates.forEach(p => addPolygon(p, props));
    }
    if (geojson.type === 'FeatureCollection') {
      geojson.features.forEach(f => processGeom(f.geometry, f.properties));
    }
    return features;
  }

  // Ray-casting point-in-polygon
  function pointInPoly(lat, lon, ring) {
    let inside = false;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const xi = ring[i][0], yi = ring[i][1];
      const xj = ring[j][0], yj = ring[j][1];
      if (((yi > lon) !== (yj > lon)) &&
          (lat < (xj - xi) * (lon - yi) / (yj - yi) + xi)) {
        inside = !inside;
      }
    }
    return inside;
  }

